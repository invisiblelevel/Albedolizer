def svg_icon(name: str, color: str = "#9aa0a6", size: int = 16,
             stroke_width: float = 1.75) -> str:
    """
    Собирает готовый SVG-стринг с нужным цветом и размером.

    name — ключ из LUCIDE_PATHS
    color — hex-цвет (#9aa0a6)
    size — размер в пикселях
    stroke_width — толщина линии (Lucide по умолчанию 2, у нас 1.75 — тоньше, элегантнее)
    """
    path = LUCIDE_PATHS.get(name, "")
    if not path:
        return ""
    # fill="currentColor" в некоторых путях → заменяем на конкретный цвет
    path = path.replace("currentColor", color)
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" '
        f'width="{size}" height="{size}" viewBox="0 0 24 24" '
        f'fill="none" stroke="{color}" stroke-width="{stroke_width}" '
        f'stroke-linecap="round" stroke-linejoin="round">{path}</svg>'
    )


def img_icon(name: str, color: str = "#9aa0a6", size: int = 16,
             stroke_width: float = 1.75) -> ft.Image:
    """
    ft.Image из инлайн-SVG через data URI.

    Работает во Flet 1.0. Не требует assets/, spec, путей.
    Цвет — любой hex.
    """
    svg = svg_icon(name, color, size, stroke_width)
    if not svg:
        # Пустая заглушка, чтобы не падало
        return ft.Container(width=size, height=size)
    b64 = base64.b64encode(svg.encode("utf-8")).decode("ascii")
    return ft.Image(
        src=f"data:image/svg+xml;base64,{b64}",
        width=size,
        height=size,
        fit=ft.BoxFit.CONTAIN,
    )


def has_icon(name: str) -> bool:
    """Проверка, есть ли иконка в словаре."""
    return name in LUCIDE_PATHS


def list_icons() -> list:
    """Список всех доступных имён иконок — для дебага."""
    return sorted(LUCIDE_PATHS.keys())